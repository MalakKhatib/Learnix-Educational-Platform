<?php

namespace App\Http\Controllers;

use Illuminate\Http\Request;
use App\Models\Quiz;
use App\Models\Result;
use App\Models\UserAnswer;
use App\Models\QuizAttempt;

class StudentQuizController extends Controller
{
    /*
    |--------------------------------------------------------------------------
    | عرض الاختبار
    |--------------------------------------------------------------------------
    */

    public function show($quiz_id)
    {
        $quiz = Quiz::with('questions.answers')
            ->findOrFail($quiz_id);

        $userId = auth()->id();

        /*
        |--------------------------------------------------------------------------
        | عدد المحاولات السابقة
        |--------------------------------------------------------------------------
        */

        $attemptsCount = QuizAttempt::where(
            'user_id',
            $userId
        )
        ->where(
            'quiz_id',
            $quiz_id
        )
        ->count();


        /*
        |--------------------------------------------------------------------------
        | لا نمنع عرض الصفحة هنا
        |
        | إذا كان الطالب قد استنفد المحاولتين،
        | صفحة Blade نفسها ستعرض رسالة انتهاء المحاولات
        |--------------------------------------------------------------------------
        */

        return view(
            'student.quizzes.show',
            compact(
                'quiz',
                'attemptsCount'
            )
        );
    }


    /*
    |--------------------------------------------------------------------------
    | تسليم الاختبار
    |--------------------------------------------------------------------------
    */

    public function submit(
        Request $request,
        $quiz_id
    ) {
        $quiz = Quiz::with('questions.answers')
            ->findOrFail($quiz_id);

        $userId = auth()->id();


        /*
        |--------------------------------------------------------------------------
        | عدد المحاولات السابقة
        |--------------------------------------------------------------------------
        */

        $attemptsCount = QuizAttempt::where(
            'user_id',
            $userId
        )
        ->where(
            'quiz_id',
            $quiz_id
        )
        ->count();


        /*
        |--------------------------------------------------------------------------
        | حماية حقيقية من المحاولة الثالثة
        |--------------------------------------------------------------------------
        */

        if ($attemptsCount >= 2) {

            return redirect(
                '/quizzes/' . $quiz_id
            )->with(
                'error',
                'لقد استنفدت جميع المحاولات المتاحة لهذا الاختبار. يمكنك حل الاختبار مرتين فقط.'
            );
        }


        /*
        |--------------------------------------------------------------------------
        | إجابات الطالب
        |--------------------------------------------------------------------------
        */

        $answers = $request->input(
            'answers',
            []
        );


        /*
        |--------------------------------------------------------------------------
        | رقم المحاولة
        |--------------------------------------------------------------------------
        */

        $attemptNumber =
            $attemptsCount + 1;


        /*
        |--------------------------------------------------------------------------
        | إنشاء محاولة جديدة
        |--------------------------------------------------------------------------
        */

        $attempt = QuizAttempt::create([

            'user_id' => $userId,

            'quiz_id' => $quiz_id,

            'score' => 0,

            'attempt_number' => $attemptNumber,

        ]);


        /*
        |--------------------------------------------------------------------------
        | حساب العلامة
        |--------------------------------------------------------------------------
        */

        $score = 0;


        foreach ($quiz->questions as $question) {

            $selected =
                $answers[$question->id] ?? null;


            /*
            |--------------------------------------------------------------------------
            | تحويل الإجابة إلى رقم
            |--------------------------------------------------------------------------
            */

            if ($selected !== null) {

                $selected =
                    (int) trim($selected);

            }


            /*
            |--------------------------------------------------------------------------
            | الإجابة الصحيحة
            |--------------------------------------------------------------------------
            */

            $correctAnswer =
                $question->answers
                    ->where(
                        'is_correct',
                        true
                    )
                    ->first();


            $isCorrect = false;


            /*
            |--------------------------------------------------------------------------
            | التحقق من صحة الإجابة
            |--------------------------------------------------------------------------
            */

            if (
                $selected !== null &&
                $correctAnswer &&
                $selected ===
                    (int) $correctAnswer->id
            ) {

                $score++;

                $isCorrect = true;
            }


            /*
            |--------------------------------------------------------------------------
            | حفظ إجابة الطالب
            |--------------------------------------------------------------------------
            */

            if ($selected !== null) {

                UserAnswer::create([

                    'attempt_id' =>
                        $attempt->id,

                    'question_id' =>
                        $question->id,

                    'answer_id' =>
                        $selected,

                    'is_correct' =>
                        $isCorrect,

                ]);
            }
        }


        /*
        |--------------------------------------------------------------------------
        | تحديث علامة المحاولة
        |--------------------------------------------------------------------------
        */

        $attempt->update([

            'score' => $score

        ]);


        /*
        |--------------------------------------------------------------------------
        | عدد الأسئلة
        |--------------------------------------------------------------------------
        */

        $totalQuestions =
            $quiz->questions->count();


        /*
        |--------------------------------------------------------------------------
        | عرض النتيجة
        |--------------------------------------------------------------------------
        */

        return view(
            'student.quizzes.result',
            [
                'score' =>
                    $score,

                'totalQuestions' =>
                    $totalQuestions,

                'quiz' =>
                    $quiz,

                'attemptNumber' =>
                    $attemptNumber,
            ]
        );
    }
}
