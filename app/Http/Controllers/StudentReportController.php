<?php

namespace App\Http\Controllers;

use App\Models\Course;
use App\Models\Lesson;
use App\Models\Progress;
use App\Models\QuizAttempt;

class StudentReportController extends Controller
{
    public function index()
    {
        $user = auth()->user();


        /*
        |--------------------------------------------------------------------------
        | الكورسات المسجل بها الطالب
        |--------------------------------------------------------------------------
        */

        $enrolledCourses = $user
            ->enrolledCourses()
            ->with('lessons')
            ->get();


        /*
        |--------------------------------------------------------------------------
        | إجمالي الكورسات
        |--------------------------------------------------------------------------
        */

        $totalCourses = $enrolledCourses->count();


        /*
        |--------------------------------------------------------------------------
        | إجمالي الدروس في الكورسات المسجل بها الطالب
        |--------------------------------------------------------------------------
        */

        $totalLessons = $enrolledCourses
            ->sum(function ($course) {

                return $course->lessons->count();

            });


        /*
        |--------------------------------------------------------------------------
        | الدروس المكتملة
        |--------------------------------------------------------------------------
        */

        $completedLessons = Progress::where(
            'user_id',
            $user->id
        )
        ->where(
            'completed',
            true
        )
        ->count();


        /*
        |--------------------------------------------------------------------------
        | الدروس المتبقية
        |--------------------------------------------------------------------------
        */

        $remainingLessons = max(
            0,
            $totalLessons - $completedLessons
        );


        /*
        |--------------------------------------------------------------------------
        | نسبة إكمال الدروس
        |--------------------------------------------------------------------------
        */

        $completionPercentage = 0;

        if ($totalLessons > 0) {

            $completionPercentage = min(
                100,
                round(
                    ($completedLessons / $totalLessons) * 100
                )
            );

        }


        /*
        |--------------------------------------------------------------------------
        | عدد محاولات الاختبارات
        |--------------------------------------------------------------------------
        */

        $totalQuizzes = QuizAttempt::where(
            'user_id',
            $user->id
        )->count();
/*
|--------------------------------------------------------------------------
| متوسط النتائج بالنسبة المئوية
|--------------------------------------------------------------------------
*/

$allAttempts = QuizAttempt::with('quiz.questions')
    ->where(
        'user_id',
        $user->id
    )
    ->get();

$averageScore = 0;

if ($allAttempts->count() > 0) {

    $totalPercentages = 0;

    foreach ($allAttempts as $attempt) {

        $totalQuestions = $attempt->quiz->questions->count();

        $percentage = 0;

        if ($totalQuestions > 0) {

            $percentage = (
                $attempt->score /
                $totalQuestions
            ) * 100;

        }

        $totalPercentages += $percentage;
    }

    $averageScore = round(
        $totalPercentages / $allAttempts->count()
    );
}

        /*
        |--------------------------------------------------------------------------
        | آخر الكورسات
        |--------------------------------------------------------------------------
        */

        $latestCourses = $user
            ->enrolledCourses()
            ->latest()
            ->take(5)
            ->get();


        /*
        |--------------------------------------------------------------------------
        | آخر محاولات الاختبارات
        |--------------------------------------------------------------------------
        */

        $latestAttempts = QuizAttempt::with([
            'quiz.questions',
            'quiz.course'
        ])
        ->where(
            'user_id',
            $user->id
        )
        ->latest()
        ->take(5)
        ->get();


        /*
        |--------------------------------------------------------------------------
        | ترتيب بيانات المخطط
        |--------------------------------------------------------------------------
        |
        | latestAttempts مرتبة من الأحدث إلى الأقدم،
        | لكن المخطط يجب أن يعرض الاختبارات من الأقدم إلى الأحدث.
        |
        */

        $chartAttempts = $latestAttempts
            ->sortBy('created_at')
            ->values();


        /*
        |--------------------------------------------------------------------------
        | بيانات مخطط الاختبارات
        |--------------------------------------------------------------------------
        */

        $quizLabels = [];

        $quizScores = [];


        foreach ($chartAttempts as $index => $attempt) {

            /*
            |--------------------------------------------------------------
            | اسم الاختبار حسب ترتيبه الزمني
            |--------------------------------------------------------------
            */

            $quizLabels[] =
                'الاختبار ' . ($index + 1);


            /*
            |--------------------------------------------------------------
            | عدد أسئلة الاختبار
            |--------------------------------------------------------------
            */

            $totalQuestions =
                $attempt->quiz->questions->count();


            /*
            |--------------------------------------------------------------
            | حساب النسبة المئوية
            |--------------------------------------------------------------
            */

            $percentage = 0;


            if ($totalQuestions > 0) {

                $percentage = round(

                    ($attempt->score /
                    $totalQuestions) * 100

                );

            }


            /*
            |--------------------------------------------------------------
            | إضافة النتيجة للمخطط
            |--------------------------------------------------------------
            */

            $quizScores[] = $percentage;

        }


        /*
        |--------------------------------------------------------------------------
        | إرسال البيانات للصفحة
        |--------------------------------------------------------------------------
        */

        return view(

            'student.reports.index',

            compact(

                'totalCourses',

                'totalLessons',

                'completedLessons',

                'remainingLessons',

                'completionPercentage',

                'totalQuizzes',

                'averageScore',

                'latestCourses',

                'latestAttempts',

                'quizLabels',

                'quizScores'

            )

        );
    }
}
